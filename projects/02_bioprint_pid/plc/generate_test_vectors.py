"""Generate reference test vectors for the Structured Text function blocks.

The default closed-loop scenario is run in Python. Then the exact inputs each
block saw (setpoint + sensor reading per scan) are recorded together with the
outputs the Python reference produced. A controls engineer can replay those
inputs open-loop through FB_BioPrintPID / FB_WestgardMonitor in TwinCAT or
CODESYS and check they get the same outputs.

Writes:
    plc/test_vectors/pid_reference.csv
    plc/test_vectors/westgard_reference.csv
    plc/src/DUT_ReferenceVectors.st      (ST struct types for the vectors)
    plc/src/GVL_ReferenceVectors.st      (the same data as ST constant arrays, for TcUnit)

Run from the project folder:  python plc/generate_test_vectors.py
"""

from __future__ import annotations

import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "src"))

import pandas as pd  # noqa: E402
from app import simulate  # noqa: E402
from config import load_config  # noqa: E402
from pid_controller import DiscretePID  # noqa: E402
from westgard_validator import BiomedicalQAMonitor  # noqa: E402


def st_real(x: float) -> str:
    """IEC 61131-3 LREAL literal (needs a decimal point; exponent allowed)."""
    return f"{x:.15E}"


def build_vectors() -> tuple[pd.DataFrame, pd.DataFrame, float]:
    cfg = load_config()
    sc, ctl, q = cfg.scenario, cfg.controller, cfg.qc
    closed_loop = simulate(cfg).frame

    # Replay open-loop through fresh Python blocks, exactly as the PLC test will.
    pid = DiscretePID(
        ctl.gains,
        dt=sc.dt,
        out_min=ctl.out_min,
        out_max=ctl.out_max,
        derivative_filter_n=ctl.derivative_filter_n,
    )
    qc = BiomedicalQAMonitor(
        target=sc.setpoint,
        baseline_start=q.baseline_start,
        baseline_length=q.baseline_length,
        dt=sc.dt,
        rolling_window=q.rolling_window,
        min_sd=q.min_sd,
    )
    pid_rows, qc_rows = [], []
    for row in closed_loop.itertuples():
        out = pid.update(row.setpoint_c, row.measured_c)
        p, i, d = pid.last_terms
        pid_rows.append(
            {
                "scan": row.step,
                "setpoint": row.setpoint_c,
                "measurement": row.measured_c,
                "output": out,
                "p_term": p,
                "i_term": i,
                "d_term": d,
            }
        )
        rules = {v.rule for v in qc.evaluate(row.step, row.measured_c)}
        qc_rows.append(
            {
                "step": row.step,
                "value": row.measured_c,
                "warn_1_2s": "1-2s" in rules,
                "reject_1_3s": "1-3s" in rules,
                "reject_2_2s": "2-2s" in rules,
                "armed": qc.is_armed,
            }
        )
    return pd.DataFrame(pid_rows), pd.DataFrame(qc_rows), float(qc.baseline_sd or 0.0)


DUT_TEXT = """(* =============================================================================
   DUT_ReferenceVectors — GENERATED by plc/generate_test_vectors.py. Do not edit.
   Struct types for GVL_ReferenceVectors (two DUTs in TwinCAT / CODESYS).
   ============================================================================= *)
TYPE ST_PidVector :
STRUCT
    lrSetpoint    : LREAL;
    lrMeasurement : LREAL;
    lrOutput      : LREAL;
    lrITerm       : LREAL;
END_STRUCT
END_TYPE

TYPE ST_WestgardVector :
STRUCT
    diStep     : DINT;
    lrValue    : LREAL;
    bWarn12s   : BOOL;
    bReject13s : BOOL;
    bReject22s : BOOL;
END_STRUCT
END_TYPE
"""


def render_gvl(pid: pd.DataFrame, qc: pd.DataFrame, baseline_sd: float) -> str:
    n = len(pid)
    pid_items = ",\n".join(
        f"        (lrSetpoint := {st_real(r.setpoint)}, lrMeasurement := {st_real(r.measurement)},"
        f" lrOutput := {st_real(r.output)}, lrITerm := {st_real(r.i_term)})"
        for r in pid.itertuples()
    )
    qc_items = ",\n".join(
        f"        (diStep := {r.step}, lrValue := {st_real(r.value)},"
        f" bWarn12s := {str(r.warn_1_2s).upper()}, bReject13s := {str(r.reject_1_3s).upper()},"
        f" bReject22s := {str(r.reject_2_2s).upper()})"
        for r in qc.itertuples()
    )
    return f"""(* =============================================================================
   GVL_ReferenceVectors — GENERATED by plc/generate_test_vectors.py. Do not edit.
   Inputs and outputs of the Python reference implementation for the default
   scenario (config/default.toml), replayed scan by scan in the TcUnit tests.
   Types: DUT_ReferenceVectors.st
   ============================================================================= *)
{{attribute 'qualified_only'}}
VAR_GLOBAL CONSTANT
    N_VECTORS       : INT   := {n};
    LR_BASELINE_SD  : LREAL := {st_real(baseline_sd)};
    aPid : ARRAY[1..{n}] OF ST_PidVector := [
{pid_items}
    ];
    aWestgard : ARRAY[1..{n}] OF ST_WestgardVector := [
{qc_items}
    ];
END_VAR
"""


def write_all(out_dir: Path = HERE) -> list[Path]:
    pid, qc, sd = build_vectors()
    vectors = out_dir / "test_vectors"
    src = out_dir / "src"
    vectors.mkdir(parents=True, exist_ok=True)
    src.mkdir(parents=True, exist_ok=True)
    paths = [
        vectors / "pid_reference.csv",
        vectors / "westgard_reference.csv",
        src / "DUT_ReferenceVectors.st",
        src / "GVL_ReferenceVectors.st",
    ]
    pid.to_csv(paths[0], index=False, float_format="%.15E")
    qc.to_csv(paths[1], index=False, float_format="%.15E")
    paths[2].write_text(DUT_TEXT)
    paths[3].write_text(render_gvl(pid, qc, sd))
    return paths


if __name__ == "__main__":
    for path in write_all():
        print(f"wrote {path.relative_to(HERE.parent)}")
